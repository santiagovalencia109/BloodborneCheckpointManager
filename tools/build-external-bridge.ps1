param([Parameter(Mandatory=$true)][string]$Clang64Bin)
$ErrorActionPreference='Stop'
$project=Split-Path -Parent $PSScriptRoot
$Clang64Bin=[IO.Path]::GetFullPath($Clang64Bin)
$env:PATH=$Clang64Bin+';'+$env:PATH
$cmake=Join-Path $Clang64Bin 'cmake.exe'
$build=Join-Path $project 'artifacts\external-native-build'
& $cmake -S (Join-Path $project 'native\external') -B $build -G Ninja -DCMAKE_BUILD_TYPE=Release -DCMAKE_C_COMPILER=clang -DCMAKE_CXX_COMPILER=clang++ -DCMAKE_ASM_COMPILER=clang
if ($LASTEXITCODE) { throw 'Native configuration failed.' }
& $cmake --build $build
if ($LASTEXITCODE) { throw 'Native build failed.' }
& (Join-Path $Clang64Bin 'ctest.exe') --test-dir $build --output-on-failure
if ($LASTEXITCODE) { throw 'Native ABI verification failed.' }
$dll=Join-Path $build 'bcm-external.dll'
$hash=(Get-FileHash -LiteralPath $dll -Algorithm SHA256).Hash
$identity=@"
// Generated by tools/build-external-bridge.ps1. Keep the companion DLL and this assembly together.
namespace Checkpoint.Core;
internal static class ExternalBridgeIdentity
{
    internal const string Sha256 = "$hash";
}
"@
Set-Content -LiteralPath (Join-Path $project 'src\Checkpoint.Core\ExternalBridgeIdentity.g.cs') -Value $identity -Encoding UTF8
foreach ($target in @('src\Checkpoint.App','tests\Checkpoint.LiveProbe')) {
    & dotnet build (Join-Path $project ($target+'\'+(Split-Path -Leaf $target)+'.csproj')) -c Release --no-restore
    if ($LASTEXITCODE) { throw '.NET build failed; restore the projects first.' }
    $output=Join-Path $project ($target+'\bin\Release\net8.0-windows\Native')
    New-Item -ItemType Directory -Path $output -Force | Out-Null
    Copy-Item -LiteralPath $dll -Destination (Join-Path $output 'bcm-external.dll')
}
Write-Output ('Built external bridge '+$hash)
