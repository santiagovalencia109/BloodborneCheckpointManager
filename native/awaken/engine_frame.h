inline void* VerifiedAwakenFrame(void* target,uintptr_t host) {
    if(!host) return nullptr;
    unsigned char entry[17]; SIZE_T count=0;
    if(!ReadProcessMemory(GetCurrentProcess(),target,entry,sizeof(entry),&count) || count!=sizeof(entry)) return nullptr;
    const unsigned char jump[]={0xff,0x25,0,0,0,0};
    if(std::memcmp(entry,jump,6) || entry[14]!=0xcc || entry[15]!=0xcc || entry[16]!=0xcc) return nullptr;
    uintptr_t destination=0; std::memcpy(&destination,entry+6,8);
    const auto expected=AwakenFrameStub(host,reinterpret_cast<uintptr_t>(target)+17);
    std::array<unsigned char,219> actual{};
    MEMORY_BASIC_INFORMATION region{};
    if(!VirtualQuery(reinterpret_cast<void*>(destination),&region,sizeof(region)) || region.State!=MEM_COMMIT ||
        (region.Protect&0xff)!=PAGE_EXECUTE_READ || region.Type!=MEM_PRIVATE) return nullptr;
    // The callback belongs to the exact hash-verified engine and has its reviewed entry.
    const unsigned char prefix[]={0x55,0x41,0x57,0x41,0x56,0x41,0x54,0x53,0x48,0x83,0xec,0x40,0x48,0x8d,0x6c,0x24,0x40};
    unsigned char callback[sizeof(prefix)];
    if(!ReadProcessMemory(GetCurrentProcess(),reinterpret_cast<void*>(host+0x119f80),callback,sizeof(callback),&count) ||
        count!=sizeof(callback) || std::memcmp(callback,prefix,sizeof(prefix))) return nullptr;
    if(!ReadProcessMemory(GetCurrentProcess(),reinterpret_cast<void*>(destination),actual.data(),actual.size(),&count) ||
        count!=actual.size() || actual!=expected) return nullptr;
    return reinterpret_cast<void*>(destination);
}
